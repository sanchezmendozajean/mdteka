import {
  Book,
  BookOpen,
  Bookmark,
  Briefcase,
  Calculator,
  ChartBar,
  ClipboardList,
  Code,
  Cpu,
  Database,
  FileText,
  Flag,
  Folder,
  FolderTree,
  GraduationCap,
  Globe,
  Heart,
  Layers,
  Library,
  Lightbulb,
  Rocket,
  Scale,
  Settings,
  Shield,
  Star,
  Users,
  Wrench,
  type LucideIcon,
} from 'lucide-react';

/** Íconos de Lucide que se pueden elegir para colecciones y libros (`icon` en el `.mdteca`). */
export const PROJECT_ICONS: Record<string, LucideIcon> = {
  book: Book,
  'book-open': BookOpen,
  bookmark: Bookmark,
  briefcase: Briefcase,
  calculator: Calculator,
  'chart-bar': ChartBar,
  'clipboard-list': ClipboardList,
  code: Code,
  cpu: Cpu,
  database: Database,
  'file-text': FileText,
  flag: Flag,
  folder: Folder,
  'folder-tree': FolderTree,
  'graduation-cap': GraduationCap,
  globe: Globe,
  heart: Heart,
  layers: Layers,
  library: Library,
  lightbulb: Lightbulb,
  rocket: Rocket,
  scale: Scale,
  settings: Settings,
  shield: Shield,
  star: Star,
  users: Users,
  wrench: Wrench,
};

/** Ícono de un nombre de Lucide; si no está en la lista se usa el predeterminado del tipo. */
export const projectIcon = (name: string | undefined, fallback: LucideIcon): LucideIcon =>
  (name && PROJECT_ICONS[name]) || fallback;
